#!/usr/bin/env python
# -*- coding: utf-8 -*-

"""
setup for the pyossia project
"""

# Always prefer setuptools over distutils
from setuptools import setup, find_packages
from setuptools.command.build_py import build_py as _build_py
import re
import sys

# To use a consistent encoding
from codecs import open
from os import path
HERE = path.abspath(path.dirname(__file__))
# Get the long description from the README file
with open(path.join(HERE, 'README.rst'), encoding='utf-8') as f:
    LONG_DESCRIPTION = f.read()

# get current version
# debian/changelog is the single version source of this CUEMS fork: the deb
# and the wheel must carry the same cuemsN revision. See README.md
# "CUEMS fork: versioning and releases" for the scheme and the mapping.
CHANGELOG = path.join(HERE, 'debian', 'changelog')
_PRERELEASE = re.compile(r'^(a|b|rc)\d+$')
_PEP440 = re.compile(r'^\d+(\.\d+)*((a|b|rc)\d+)?(\+[a-z0-9]+(\.[a-z0-9]+)*)?$')


def debian_version(changelog):
    """Version of the newest entry of a debian/changelog."""
    with open(changelog, encoding='utf-8') as f:
        match = re.match(r'^\S+ \(([^()\s]+)\)', f.readline())
    if not match:
        sys.exit("ERROR: setup.py: cannot read a version from " + changelog)
    return match.group(1)


def pep440_version(deb_version):
    """Map a debian version onto PEP 440.

    2.0.0-rc6+124+cuems3 -> 2.0.0rc6+124.cuems.3
    2.0.1-cuems          -> 2.0.1+cuems
    2.0.1-cuems1         -> 2.0.1+cuems.1

    A pre-release debian revision (rcN, aN, bN) joins the public version;
    any other revision and every +part go to the local label. Trailing
    digits are split into their own segment (cuems3 -> cuems.3) because
    PEP 440 compares a mixed segment as text: cuems10 would sort below cuems9.
    """
    public, _, plus = deb_version.lower().partition('+')
    upstream, _, revision = public.partition('-')
    local = plus.split('+') if plus else []
    if _PRERELEASE.match(revision):
        upstream += revision
    elif revision:
        local.insert(0, revision)
    local = [s for part in local
             for s in re.sub(r'^([a-z]+)(\d+)$', r'\1.\2', part).split('.')]
    version = upstream + ('+' + '.'.join(local) if local else '')
    if not _PEP440.match(version):
        sys.exit("ERROR: setup.py: debian version %r maps to %r, which is not "
                 "a PEP 440 version" % (deb_version, version))
    return version


__version__ = pep440_version(debian_version(CHANGELOG))


class build_py(_build_py):
    """Freeze the version into the built pyossia/_version.py.

    The tracked _version.py asks git at import time, which an installed copy
    cannot do: every wheel and deb reported pyossia.__version__ "0+unknown".
    """
    def run(self):
        _build_py.run(self)
        target = path.join(self.build_lib, 'pyossia', '_version.py')
        with open(target, 'w', encoding='utf-8') as f:
            f.write('# Generated by setup.py from debian/changelog.\n\n'
                    'def get_versions():\n'
                    '    return {"version": %r, "debian-version": %r,\n'
                    '            "full-revisionid": None, "dirty": None,\n'
                    '            "error": None, "date": None}\n'
                    % (__version__, debian_version(CHANGELOG)))


try:
    from wheel.bdist_wheel import bdist_wheel as _bdist_wheel
    class bdist_wheel(_bdist_wheel):
        def finalize_options(self):
            _bdist_wheel.finalize_options(self)
            self.root_is_pure = False
except ImportError:
    sys.exit("ERROR: setup.py: you must install wheel (pip2/3 install wheel)")

